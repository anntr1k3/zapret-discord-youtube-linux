"""Guarded original-service transaction for the installed strategy tester.

Used by the installed stream; the GUI capability stays gated until integration.
No config rewrites, adoption of foreign processes or broad cleanup on failure.
"""

import hashlib
import importlib.util
import json
from pathlib import Path, PurePosixPath
import re
import stat
import subprocess


SERVICE = "zapret_discord_youtube.service"
ENV = {"PATH": "/usr/sbin:/usr/bin:/sbin:/bin", "LC_ALL": "C", "HOME": "/"}


def load_runtime():
    path = Path(__file__).with_name("strategy_test_runtime.py")
    spec = importlib.util.spec_from_file_location("installed_session_runtime", path)
    module = importlib.util.module_from_spec(spec)
    exec(compile(path.read_bytes(), str(path), "exec"), module.__dict__)
    return module


def starttime(data):
    try:
        value = data.decode("ascii").rsplit(") ", 1)[1].split()[19]
    except (UnicodeError, IndexError) as error:
        raise ValueError("Invalid engine process identity") from error
    if not value.isdigit():
        raise ValueError("Invalid engine start time")
    return value


def engine_processes(release, proc=Path("/proc")):
    read = load_runtime().read_regular
    expected = str(Path(release) / "nfqws")
    result = []
    for folder in sorted(Path(proc).iterdir(), key=lambda path: path.name):
        if not folder.name.isdigit():
            continue
        try:
            executable = str((folder / "exe").readlink())
        except FileNotFoundError:
            continue  # Kernel thread or process already gone before observation.
        if executable == expected + " (deleted)":
            raise ValueError("Installed engine executable has been replaced")
        if executable != expected:
            continue
        identity = starttime(read(folder / "stat", 65536))
        membership = read(folder / "cgroup", 65536).decode("utf-8")
        groups = [line[3:] for line in membership.splitlines() if line.startswith("0::")]
        if len(groups) != 1:
            raise ValueError("Cannot prove engine cgroup ownership")
        argv = read(folder / "cmdline", 65536).split(b"\0")
        queues = [arg for arg in argv if arg.startswith(b"--qnum=")]
        if len(queues) != 1 or not re.fullmatch(rb"--qnum=[0-9]{1,5}", queues[0]):
            raise ValueError("Cannot prove engine queue")
        queue = int(queues[0].split(b"=", 1)[1])
        if (queue > 65535 or starttime(read(folder / "stat", 65536)) != identity
                or str((folder / "exe").readlink()) != executable
                or read(folder / "cgroup", 65536).decode("utf-8") != membership):
            raise ValueError("Engine identity changed during observation")
        result.append({"pid": int(folder.name), "starttime": identity, "group": groups[0], "queue": queue})
    return sorted(result, key=lambda entry: entry["pid"])


def validate_engines(engines, *, active, group):
    if not active:
        if engines:
            raise ValueError("Engine exists outside the inactive managed service")
        return
    parts = PurePosixPath(group).parts
    if not group.startswith("/") or ".." in parts or parts[-1:] != (SERVICE,):
        raise ValueError("Unknown managed service cgroup")
    if any(engine["group"] != group for engine in engines):
        raise ValueError("Same-executable engine exists outside the managed service; stop it manually first")
    if len(engines) != 1 or engines[0]["queue"] != 220:
        raise ValueError("Managed service engine/queue is not unambiguously owned")


def port_values(value):
    if type(value) is int and 1 <= value <= 65535:
        return {value}
    if isinstance(value, dict) and set(value) == {"range"}:
        bounds = value["range"]
        if (isinstance(bounds, list) and len(bounds) == 2
                and all(type(item) is int for item in bounds) and 1 <= bounds[0] <= bounds[1] <= 65535):
            return set(range(bounds[0], bounds[1] + 1))
    if isinstance(value, dict) and set(value) == {"set"} and isinstance(value["set"], list) and value["set"]:
        result = set()
        for item in value["set"]:
            result.update(port_values(item))
        return result
    raise ValueError("Unknown capture port expression")


def configured_ports(text):
    if not text:
        return set()
    result = set()
    for item in text.split(","):
        if not re.fullmatch(r"[0-9]{1,5}(?:-[0-9]{1,5})?", item):
            raise ValueError("Unknown configured capture ports")
        ends = [int(number) for number in item.split("-")]
        result.update(port_values(ends[0] if len(ends) == 1 else {"range": ends}))
    return result


def inspect_table(document, plan, interface, *, active):
    """Accept only the exact rule semantics generated by the nft backend."""
    if not isinstance(document, dict) or not isinstance(document.get("nftables"), list):
        raise ValueError("Unknown nftables state")
    related = []
    for entry in document["nftables"]:
        if not isinstance(entry, dict):
            raise ValueError("Invalid nftables entry")
        for kind, value in entry.items():
            if isinstance(value, dict) and value.get("family") == "inet" and (
                    (kind == "table" and value.get("name") == "zapretunix") or value.get("table") == "zapretunix"):
                related.append((kind, value))
    if not active:
        if related:
            raise ValueError("Inactive service has existing app table; refusing to adopt/delete it")
        return None
    tables = [value for kind, value in related if kind == "table"]
    chains = [value for kind, value in related if kind == "chain"]
    if len(tables) != 1 or len(chains) != 2 or {chain.get("name") for chain in chains} != {"pre", "post"}:
        raise ValueError("Unknown managed nft table/chains")
    for chain in chains:
        hook, priority = ("postrouting", -150) if chain["name"] == "post" else ("prerouting", 0)
        if (set(chain) - {"family", "table", "name", "handle", "type", "hook", "prio", "policy"}
                or (chain.get("type"), chain.get("hook"), chain.get("prio"), chain.get("policy")) !=
                ("filter", hook, priority, "accept")):
            raise ValueError("Managed nft hook changed")
    expected = []
    tcp, udp = configured_ports(plan["tcp_ports"]), configured_ports(plan["udp_ports"])
    for chain, protocol, ports in (("post", "tcp", tcp), ("post", "udp", udp), ("pre", "tcp", tcp)):
        if ports:
            expected.append((chain, protocol, tuple(sorted(ports))))
    observed = []
    loopback_policies = set()
    for kind, rule in related:
        if kind in ("table", "chain"):
            continue
        if kind != "rule" or rule.get("comment") != "Added by zapret script" or rule.get("chain") not in ("pre", "post"):
            raise ValueError("Foreign object/rule in app table")
        expr = rule.get("expr")
        if (not isinstance(expr, list) or not expr or expr[-1] not in (
                {"queue": {"num": 220, "flags": ["bypass"]}},
                {"queue": {"num": 220, "flags": "bypass"}})):
            raise ValueError("Managed nft queue/verdict changed")
        chain = rule["chain"]
        matches = []
        interface_key = {"meta": {"key": "oifname" if chain == "post" else "iifname"}}
        excludes_loopback = False
        for item in expr[:-1]:
            if not isinstance(item, dict) or set(item) != {"match"}:
                raise ValueError("Unknown effect in managed nft rule")
            match = item["match"]
            if not isinstance(match, dict) or set(match) != {"op", "left", "right"}:
                raise ValueError("Unknown managed nft match")
            if match["op"] == "!=" and interface == "any" and not excludes_loopback \
                    and match["left"] == interface_key and match["right"] == "lo":
                excludes_loopback = True
                continue
            if match["op"] not in ("==", "in"):
                raise ValueError("Unknown managed nft match")
            matches.append((match["left"], match["right"]))
        loopback_policies.add(excludes_loopback)
        fixed = [({"ct": {"key": "packets", "dir": "original" if chain == "post" else "reply"}},
                  {"range": [1, 6 if chain == "post" else 3]})]
        if chain == "post":
            fixed.append(({"&": [{"meta": {"key": "mark"}}, 1073741824]}, 0))
        if interface != "any":
            fixed.append((interface_key, interface))
        for pair in fixed:
            if pair not in matches:
                raise ValueError("Managed nft match changed")
            matches.remove(pair)
        if len(matches) != 1:
            raise ValueError("Foreign match in managed nft rule")
        left, right = matches[0]
        protocols = [protocol for protocol in ("tcp", "udp") if left == {
            "payload": {"protocol": protocol, "field": "dport" if chain == "post" else "sport"}}]
        if not protocols or (chain == "pre" and protocols[0] != "tcp"):
            raise ValueError("Unknown managed capture protocol")
        observed.append((chain, protocols[0], tuple(sorted(port_values(right)))))
    if sorted(observed) != sorted(expected):
        raise ValueError("Managed capture rules differ from original strategy")
    if len(loopback_policies) > 1:
        raise ValueError("Managed rules use inconsistent loopback exclusions")
    return json.dumps(related, sort_keys=True)


class ServiceGuard:
    def __init__(self, installer, *, run=subprocess.run, proc=Path("/proc")):
        self.installer, self.run, self.proc = installer, run, proc
        self.runtime = load_runtime()

    def command(self, argv, *, timeout=12):
        result = self.run(argv, capture_output=True, text=True, check=False, timeout=timeout, env=dict(ENV))
        if result.returncode or len(result.stdout) > 4 * 1024 * 1024:
            raise ValueError((result.stderr or "Cannot inspect/change managed service")[-2000:])
        return result.stdout

    def capture(self, prepared):
        text = self.command(["/usr/bin/systemctl", "show", SERVICE,
            "--property=LoadState,ActiveState,SubState,MainPID,ControlGroup,UnitFileState"])
        props = {}
        for line in text.splitlines():
            key, separator, value = line.partition("=")
            if not separator or key in props:
                raise ValueError("Unknown systemd observation")
            props[key] = value
        active = props.get("ActiveState") == "active"
        if (props.get("LoadState") != "loaded" or props.get("ActiveState") not in ("active", "inactive")
                or props.get("SubState") != ("running" if active else "dead")
                or not props.get("UnitFileState") or not re.fullmatch(r"[0-9]+", props.get("MainPID", ""))
                or (int(props["MainPID"]) > 0) != active):
            raise ValueError("Unknown/transitional/failed managed service state")
        engines = engine_processes(prepared["release"], self.proc)
        validate_engines(engines, active=active, group=props.get("ControlGroup", ""))
        table = inspect_table(json.loads(self.command(["/usr/sbin/nft", "-j", "-s", "list", "ruleset"])),
                              prepared["baseline_plan"], prepared["values"]["interface"], active=active)
        return {"active": active, "autostart": props["UnitFileState"], "main_pid": props["MainPID"],
                "group": props.get("ControlGroup", ""), "engines": engines, "table": table}

    def stamp(self, prepared):
        state = self.installer.state()
        if state is None or self.installer.release(state["current"]) != prepared["release"]:
            raise ValueError("Installed release changed")
        common = self.runtime.read_regular(prepared["release"] / "src/lib/common.sh", 1024 * 1024)
        if b"# managed-service-cgroup-stop-v1:" not in common:
            raise ValueError("Installed runtime lacks cgroup-scoped service stop; update before strategy testing")
        result = {}
        total = 0
        for root in (prepared["release"], self.installer.data):
            self.installer.check_tree(root)
            for path in [root, *sorted(root.rglob("*"))]:
                info = path.lstat()
                if len(result) >= 8192:
                    raise ValueError("Too many installed files to verify")
                digest = None
                if stat.S_ISREG(info.st_mode):
                    data = self.runtime.read_regular(path, 32 * 1024 * 1024)
                    total += len(data)
                    if total > 256 * 1024 * 1024:
                        raise ValueError("Installed inputs exceed verification limits")
                    digest = hashlib.sha256(data).hexdigest()
                elif not stat.S_ISDIR(info.st_mode):
                    raise ValueError("Unsafe installed input")
                result[str(path)] = (stat.S_IMODE(info.st_mode), info.st_uid, info.st_gid, digest)
        self.installer.check_path(self.installer.unit)
        result["unit"] = hashlib.sha256(self.runtime.read_regular(self.installer.unit, 65536)).hexdigest()
        if self.runtime.read_regular(self.installer.data / "conf.env", 16384) != prepared["config_bytes"]:
            raise ValueError("Installed configuration changed")
        return result

    def change(self, action):
        if action not in ("start", "stop"):
            raise ValueError("Unsupported tester service change")
        self.command(["/usr/bin/systemctl", action, SERVICE], timeout=60)


class InstalledSessionRuntime:
    """Installed stream adapter; GUI activation is gated separately."""

    def __init__(self, installer, *, guard=None, prepare=None, allocate=None):
        runtime = load_runtime()
        self.installer = installer
        self.guard = guard if guard is not None else ServiceGuard(installer)
        self.prepare = prepare if prepare is not None else runtime.prepare
        self.allocate = allocate if allocate is not None else runtime.allocate
        self.saved = None
        self.child = None
        self.entered = self.stop_attempted = self.restored = False

    def operation(self):
        return self.installer.operation()

    def snapshot(self, request):
        if self.saved is not None:
            raise ValueError("Session snapshot already exists")
        prepared = self.prepare(self.installer, request)
        stamp = self.guard.stamp(prepared)
        state = self.guard.capture(prepared)
        child = self.allocate(prepared)
        self.saved = {"prepared": prepared, "stamp": stamp, "state": state}
        self.child = child
        return self.saved

    def check(self, snapshot, *, original=False):
        if snapshot is not self.saved or self.saved is None:
            raise ValueError("Unknown session snapshot")
        if self.guard.stamp(snapshot["prepared"]) != snapshot["stamp"]:
            raise ValueError("Installed inputs changed; automatic service changes refused")
        state = self.guard.capture(snapshot["prepared"])
        if original:
            if state != snapshot["state"]:
                raise ValueError("Original service changed since snapshot")
        elif state["active"] or state["autostart"] != snapshot["state"]["autostart"]:
            raise ValueError("Service/autostart changed during test session")
        return state

    def enter(self, snapshot):
        if self.entered or self.stop_attempted or self.restored:
            raise ValueError("Session cannot be entered again")
        state = self.check(snapshot, original=True)
        if self.child.queue in self.child.resources():
            raise ValueError("Test queue changed before service stop")
        if state["active"]:
            self.stop_attempted = True  # Includes a partially failed systemctl stop.
            self.guard.change("stop")
        self.check(snapshot)
        self.entered = True

    def start(self, name):
        if not self.entered or self.restored or name not in self.saved["prepared"]["plans"]:
            raise ValueError("Unapproved profile or inactive test session")
        self.check(self.saved)
        self.child.start(name)

    def stop(self):
        if self.child is not None:
            self.child.stop()

    def restore(self, snapshot):
        if snapshot is not self.saved or self.saved is None:
            raise ValueError("Unknown session snapshot")
        if self.restored:
            return
        # Never call the original broad service start while a child/table remains
        # or ownership is uncertain. Even input drift does not skip own cleanup.
        self.stop()
        if not self.stop_attempted:
            self.check(snapshot, original=True)
        else:
            self.check(snapshot)
            self.guard.change("start")
            current = self.guard.capture(snapshot["prepared"])
            if (not current["active"] or current["autostart"] != snapshot["state"]["autostart"]
                    or self.guard.stamp(snapshot["prepared"]) != snapshot["stamp"]):
                raise ValueError("Original service restoration could not be verified")
        self.restored = True
